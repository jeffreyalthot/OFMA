def normalize_language(language_code: str | None) -> str:
    value = (language_code or "fr").strip().lower()
    return value if value in SUPPORTED_LANGUAGES else "fr"


def tr(language_code: str | None, key: str) -> str:
    lang = normalize_language(language_code)
    return (
        TRANSLATIONS.get(lang, {}).get(key)
        or TRANSLATIONS["fr"].get(key)
        or key
    )


def admin_tr(language_code: str | None, key: str) -> str:
    lang = normalize_language(language_code)
    return (
        ADMIN_TRANSLATIONS.get(lang, {}).get(key)
        or ADMIN_TRANSLATIONS["fr"].get(key)
        or key
    )
